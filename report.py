#!/usr/bin/env python3
"""Summarize results.jsonl: per-agent pass rate (with 95% Wilson interval), cost proxies, per-task matrix."""
import argparse
import csv
import json
import math
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def wilson(k, n, z=1.96):
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def cost_cell(rs):
    costs = [r["cost_usd"] for r in rs if r.get("cost_usd") is not None]
    return f"{sum(costs):.2f}" if costs else "-"


def write_markdown(path, by_agent, tasks):
    """Leaderboard regenerated from results.jsonl. Don't edit by hand: rerun report.py --md."""
    def summary(rs):
        n, k = len(rs), sum(r["pass"] for r in rs)
        lo, hi = wilson(k, n)
        last = max(rs, key=lambda r: r["timestamp"])
        setup = (last.get("agent_note") or last.get("agent_cmd") or "").replace("|", "\\|")
        return {
            "pass": k / n, "row": [
                f"**{rs[0]['agent']}**", setup, f"{k}/{n} ({k / n:.0%})", f"{lo:.0%}–{hi:.0%}",
                f"{statistics.mean(r['score'] for r in rs):.0%}",
                f"{statistics.median(r['seconds'] for r in rs):.0f}"
                + (" (manual)" if any(r.get("mode") == "manual" for r in rs) else ""),
                f"{statistics.median(r['lines_added'] + r['lines_removed'] for r in rs):.0f}",
                f"{sum(bool(r.get('tests_added_to')) for r in rs)}/{n}",
                str(sum(bool(r["tampered_files"]) for r in rs)), str(sum(r["timed_out"] for r in rs)),
                f"{statistics.median(r.get('continues', 0) for r in rs):.0f}",
                "$" + cost_cell(rs) if cost_cell(rs) != "-" else "-",
                last["timestamp"][:10],
            ]}
    rows = sorted((summary(rs) for rs in by_agent.values()), key=lambda x: -x["pass"])
    head = ["agent", "harness / model / settings", "pass", "95% CI", "tests%", "median s", "median diff",
            "added tests", "tamper", "timeouts", "continues", "cost", "last run"]
    agents = sorted(by_agent)
    out = ["# Leaderboard", "",
           "Generated by `python3 report.py --md` from `results/results.jsonl`. **Don't edit by hand.**",
           "To add a harness or model: run `run.py` with a new `--name` and a `--note` describing the setup,",
           "then rerun `python3 report.py --md` and commit this file together with `results/results.jsonl`.", "",
           "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r["row"]) + " |" for r in rows]
    out += ["", "## Passes per task", "", "| task | " + " | ".join(agents) + " |", "|" + "---|" * (len(agents) + 1)]
    for t in tasks:
        cells = []
        for a in agents:
            rs = [r for r in by_agent[a] if r["task"] == t]
            cells.append(f"{sum(r['pass'] for r in rs)}/{len(rs)}" if rs else "–")
        out.append(f"| {t} | " + " | ".join(cells) + " |")
    out += ["", "## How to read it", "",
            "- **pass**: every hidden test passed and no protected test was tampered with. If the **95% CI**s "
            "of two rows overlap heavily, there's no real difference yet: add runs or harder tasks.",
            "- **tests%**: share of hidden tests passed (partial credit).",
            "- **added tests**: runs where the agent wrote extra tests of its own (allowed, not tampering).",
            "- **median s** for *(manual)* rows includes human reaction time; compare those only with each other.",
            "- **continues**: median \"continue\" follow-ups in manual runs.",
            "- **cost**: what the agent itself reported (Claude Code `--output-format json`); `-` if it reports none.",
            "- Only compare rows run on the same task set. Rows were run on this machine with each harness's",
            "  own user config unless the setup column says otherwise."]
    Path(path).write_text("\n".join(out) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default=str(ROOT / "results" / "results.jsonl"))
    ap.add_argument("--agents", nargs="*", help="only these agent names")
    ap.add_argument("--run-id", nargs="*", help="only these run ids")
    ap.add_argument("--csv", help="also write per-run rows to this CSV")
    ap.add_argument("--md", nargs="?", const=str(ROOT / "LEADERBOARD.md"),
                    help="also write a Markdown leaderboard (default path: LEADERBOARD.md in the kit)")
    args = ap.parse_args()

    rows = [json.loads(l) for l in open(args.results) if l.strip()]
    if args.agents:
        rows = [r for r in rows if r["agent"] in args.agents]
    if args.run_id:
        rows = [r for r in rows if r["run_id"] in args.run_id]
    if not rows:
        raise SystemExit("no results")

    by_agent = defaultdict(list)
    for r in rows:
        by_agent[r["agent"]].append(r)

    print("\n== Summary ==")
    aw = max(16, max(len(a) for a in by_agent) + 2)
    hdr = f"{'agent':<{aw}}{'runs':>5}{'pass':>7}{'95% CI':>14}{'tests%':>8}{'tamper':>7}{'t/o':>5}{'med s':>8}{'med +/-':>9}{'cont':>6}{'gave':>6}{'$ total':>9}"
    print(hdr)
    print("-" * len(hdr))
    for agent, rs in sorted(by_agent.items()):
        n, k = len(rs), sum(r["pass"] for r in rs)
        lo, hi = wilson(k, n)
        print(f"{agent:<{aw}}{n:>5}{k / n:>7.0%}{f'{lo:.0%}-{hi:.0%}':>14}"
              f"{statistics.mean(r['score'] for r in rs):>8.0%}"
              f"{sum(bool(r['tampered_files']) for r in rs):>7}{sum(r['timed_out'] for r in rs):>5}"
              f"{statistics.median(r['seconds'] for r in rs):>8.0f}"
              f"{statistics.median(r['lines_added'] + r['lines_removed'] for r in rs):>9.0f}"
              f"{statistics.median(r.get('continues', 0) for r in rs):>6.0f}"
              f"{sum(r.get('gave_up', False) for r in rs):>6}"
              f"{cost_cell(rs):>9}"
              + ("  [manual]" if any(r.get("mode") == "manual" for r in rs) else ""))

    tasks = sorted({r["task"] for r in rows})
    agents = sorted(by_agent)
    print("\n== Passes per task ==")
    w = max(len(t) for t in tasks) + 2
    cw = max(16, max(len(a) for a in agents) + 2)
    print(f"{'task':<{w}}" + "".join(f"{a:>{cw}}" for a in agents))
    for t in tasks:
        cells = []
        for a in agents:
            rs = [r for r in by_agent[a] if r["task"] == t]
            cells.append(f"{sum(r['pass'] for r in rs)}/{len(rs)}" if rs else "-")
        print(f"{t:<{w}}" + "".join(f"{c:>{cw}}" for c in cells))

    print("\nNotes: 'tests%' = share of hidden tests passed (partial credit). A run passes only if every\n"
          "hidden test passes and no protected test was tampered with. Overlapping CIs = not a real difference yet.\n"
          "'$ total' = summed agent-reported cost (Claude Code --output-format json), '-' if not reported.\n"
          "'cont' = median \"continue\" follow-ups per run, 'gave' = runs abandoned. [manual] agents were\n"
          "driven by hand: their 'med s' includes human reaction time, so don't compare it with CLI agents.")

    if args.md:
        write_markdown(args.md, by_agent, tasks)
        print(f"wrote {args.md}")

    if args.csv:
        keys = ["run_id", "agent", "task", "difficulty", "repeat", "pass", "score", "tests_passed",
                "tests_total", "tampered_files", "timed_out", "seconds", "cost_usd", "mode", "continues", "gave_up",
                "agent_note", "lines_added", "lines_removed", "workdir"]
        with open(args.csv, "w", newline="") as f:
            wr = csv.DictWriter(f, fieldnames=keys, extrasaction="ignore")
            wr.writeheader()
            wr.writerows(rows)
        print(f"wrote {args.csv}")


if __name__ == "__main__":
    main()
